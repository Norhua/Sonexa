import { test, expect, type Page } from './fixtures'
import { fileURLToPath } from 'node:url'
const stub = fileURLToPath(new URL('./wails-stub.js', import.meta.url))
const rows = (page: Page) => page.locator('.track-list [data-row-key]')
const selected = (page: Page) => page.locator('.track-list [aria-selected="true"]')
async function clickRow(page: Page, index: number, modifiers: ('Shift' | 'Meta' | 'Control')[] = []) {
  await rows(page).nth(index).locator('td').last().click({ modifiers })
}
test.beforeEach(async ({ page }) => {
  await page.addInitScript({ path: stub })
  await page.addInitScript(() => localStorage.setItem('sonexa.theme', 'light'))
  await page.goto('/')
  await expect(rows(page)).toHaveCount(7)
})
test('click, modifier ranges, keyboard, right click and scoped select all', async ({ page }) => {
  await clickRow(page, 0); await expect(selected(page)).toHaveCount(1)
  await expect(page.locator('aside')).toHaveCount(0)
  await clickRow(page, 3, ['Shift']); await expect(selected(page)).toHaveCount(4)
  await clickRow(page, 1, ['Shift']); await expect(selected(page)).toHaveCount(2)
  await clickRow(page, 5, ['Meta']); await expect(selected(page)).toHaveCount(3)
  await page.keyboard.press('ArrowDown'); await expect(selected(page)).toHaveCount(1)
  await expect(rows(page).nth(6)).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Shift+ArrowUp'); await expect(selected(page)).toHaveCount(2)
  await page.keyboard.press('Meta+a'); await expect(selected(page)).toHaveCount(7)
  await rows(page).nth(2).click({ button: 'right' }); await expect(selected(page)).toHaveCount(7)
  await page.getByRole('menuitem', { name: '导出选中项…', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__lastExport?.trackIds)).toEqual([1, 2, 3, 4, 5, 6, 7])
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '设置', exact: true })
  await expect(dialog).toBeVisible()
  await expect.poll(() => dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Meta+a'); await expect(selected(page)).toHaveCount(7)
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0)
  await clickRow(page, 0); await page.keyboard.press('Enter')
  await expect(page.locator('aside')).toBeVisible()
})
test('sorting keeps stable anchor and cycles back to default through the header', async ({ page }) => {
  await clickRow(page, 0)
  const anchor = await rows(page).nth(0).getAttribute('data-row-key')
  await page.getByRole('columnheader', { name: '标题' }).click()
  await expect(page.getByRole('columnheader', { name: '标题' })).toHaveAttribute('aria-sort', 'ascending')
  const keys = await rows(page).evaluateAll(els => els.map(el => el.getAttribute('data-row-key')))
  const from = keys.indexOf(anchor)
  const target = from === 0 ? 2 : 0
  await clickRow(page, target, ['Shift'])
  await expect(selected(page)).toHaveCount(Math.abs(from - target) + 1)
  await page.getByRole('columnheader', { name: '标题' }).click()
  await expect(page.getByRole('columnheader', { name: '标题' })).toHaveAttribute('aria-sort', 'descending')
  await page.getByRole('columnheader', { name: '标题' }).click()
  await expect(rows(page).first()).toHaveAttribute('data-row-key', 'track:1')
  await expect(page.getByRole('columnheader', { name: '标题' })).toHaveAttribute('aria-sort', 'none')
})
test('text drag preserves selection and clipboard text; selected/hover differ in both themes', async ({ page }) => {
  await clickRow(page, 0)
  const title = rows(page).nth(4).locator('[data-text-cell]').first()
  const box = (await title.boundingBox())!
  await page.mouse.move(box.x + 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + 85, box.y + box.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString().length ?? 0)).toBeGreaterThan(1)
  await expect(selected(page)).toHaveCount(1)
  await expect(rows(page).first()).toHaveAttribute('aria-selected', 'true')
  // 双击文字的浏览器词语选区不能阻止打开曲目详情。
  await title.dblclick()
  await expect(page.locator('aside')).toBeVisible()
  await page.locator('aside').getByTitle('关闭', { exact: true }).click()
  for (const dark of [false, true]) {
    await page.evaluate(dark => document.documentElement.classList.toggle('dark', dark), dark)
    await rows(page).nth(1).hover()
    const color = await selected(page).evaluate(el => getComputedStyle(el).backgroundColor)
    expect(await rows(page).nth(1).evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(color)
  }
})
