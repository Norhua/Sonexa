import { test, expect, type Page } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const rows = (page: Page) => page.locator('.track-list [data-row-key]')
const selected = (page: Page) => page.locator('.track-list [aria-selected="true"]')
test.beforeEach(async ({ page }) => {
  await page.addInitScript({ path: fileURLToPath(new URL('./wails-stub.js', import.meta.url)) })
  await page.goto('/')
  await expect(rows(page)).toHaveCount(7)
})
test('ghost positions remain unique, keyboard skips them, exports deduplicate track IDs', async ({ page }) => {
  await page.getByRole('button', { name: '专辑', exact: true }).click()
  await page.getByRole('button', { name: /测试专辑/ }).click()
  await expect(rows(page)).toHaveCount(5)
  expect(new Set(await rows(page).evaluateAll(els => els.map(el => el.getAttribute('data-row-key')))).size).toBe(5)
  await rows(page).nth(0).locator('td').last().click()
  await rows(page).nth(1).locator('td').nth(2).click()
  await expect(selected(page)).toHaveCount(1)
  await page.keyboard.press('ArrowDown')
  await expect(rows(page).nth(2)).toBeFocused()
  await page.keyboard.press('Meta+a')
  await expect(selected(page)).toHaveCount(3)
  await expect(page.getByRole('status')).toContainText('2 首曲目 · 已选 2 项')
  await rows(page).nth(1).locator('td').nth(2).click({ button: 'right' })
  await expect(page.getByRole('menuitem')).toHaveCount(2)
  await expect(page.getByRole('menuitem', { name: '查看上游' })).toBeVisible()
  await expect.poll(() => page.locator('[data-pc-name="contextmenu"]').evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-pc-name="contextmenu"]')).toHaveCount(0)
  await rows(page).nth(2).locator('td').nth(2).click({ button: 'right' })
  await page.getByRole('menuitem', { name: '导出选中项…' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__lastExport?.trackIds)).toEqual([1, 2])
  await expect(page.getByRole('columnheader', { name: '标题' })).not.toHaveAttribute('tabindex', '0')
})
test('playlist reorders via native DataTable handle, never by dragging text or a filtered subset', async ({ page }) => {
  await page.getByRole('button', { name: /测试歌单/ }).click()
  const handle = rows(page).nth(4).locator('[data-pc-section="reorderablerowhandle"]')
  await expect(handle).toBeVisible()
  const target = (await rows(page).first().boundingBox())!
  await handle.hover()
  await page.mouse.down()
  await page.mouse.move(target.x + 20, target.y + 2, { steps: 15 })
  await page.mouse.move(target.x + 22, target.y + 3)
  await page.mouse.up()
  await expect.poll(() => page.evaluate(() => (window as any).__lastReorder?.ids)).toEqual([5, 1, 2, 3, 4, 6, 7])
  await page.getByRole('columnheader', { name: '标题' }).click()
  await expect(page.locator('[data-pc-section="reorderablerowhandle"]')).toHaveCount(0)
  await page.getByTitle('排序：标题').click()
  await page.getByRole('menuitem', { name: /默认顺序/ }).click()
  await page.getByRole('searchbox').fill('Tetra')
  await page.getByRole('searchbox').press('Enter')
  await expect(rows(page)).toHaveCount(1)
  await expect(page.locator('[data-pc-section="reorderablerowhandle"]')).toHaveCount(0)
})
test('keyboard context menu and viewport clamping', async ({ page }) => {
  await rows(page).first().locator('td').last().click()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menuitem', { name: '打开详情' })).toBeVisible()
  await expect.poll(() => page.locator('[data-pc-name="contextmenu"]').evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-pc-name="contextmenu"]')).toHaveCount(0)
  await rows(page).last().locator('td').last().click({ button: 'right' })
  const menu = page.locator('[data-pc-name="contextmenu"]')
  await expect(menu).toBeVisible()
  const bounds = (await menu.boundingBox())!
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(1440)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(900)
  await page.locator('nav').getByRole('button', { name: '全部曲目', exact: true }).click()
  await expect(menu).toHaveCount(0)
})
test('review Select switches upstream and refreshes candidates', async ({ page }) => {
  await page.getByRole('button', { name: /复核队列/ }).click()
  await page.getByRole('button', { name: '重新搜索', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__lastResearch?.providerID)).toBe('musicbrainz')
  await page.getByRole('combobox').click()
  await page.getByRole('option', { name: 'iTunes', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__lastResearch?.providerID)).toBe('itunes')
  await expect(page.getByRole('combobox')).toHaveCount(2)
})
